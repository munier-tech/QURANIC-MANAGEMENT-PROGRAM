// Process family fee payment
export const processFamilyFeePayment = async (req, res) => {
  try {
    const { id } = req.params;
    const { paidAmount, paymentMethod, note } = req.body;

    const familyFee = await prisma.familyFee.findUnique({
      where: { id },
      include: {
        students: {
          include: {
            student: {
              select: {
                id: true,
                fullname: true,
                studentId: true,
                class: true
              }
            }
          }
        }
      }
    });

    if (!familyFee) {
      return res.status(404).json({ message: "Family fee record not found" });
    }

    // Update payment details
    const updatedFamilyFee = await prisma.familyFee.update({
      where: { id },
      data: {
        paidAmount,
        paid: paidAmount >= familyFee.totalAmount,
        paidDate: new Date(),
        paymentMethod: paymentMethod || 'cash',
        note: note || familyFee.note
      },
      include: {
        students: {
          include: {
            student: {
              select: {
                id: true,
                fullname: true,
                studentId: true,
                class: true
              }
            }
          }
        }
      }
    });

    // Add to finance if fully paid
    if (updatedFamilyFee.paid) {
      // Check if finance record exists for this month/year
      let financeRecord = await prisma.finance.findFirst({
        where: {
          month: familyFee.month,
          year: familyFee.year
        }
      });

      if (!financeRecord) {
        financeRecord = await prisma.finance.create({
          data: {
            month: familyFee.month,
            year: familyFee.year,
            income: 0,
            expenses: 0,
            debt: 0,
            paidFeesCount: 0,
            paidSalariesCount: 0,
            unpaidFeesCount: 0,
            date: new Date(familyFee.year, familyFee.month - 1, 1)
          }
        });
      }

      // Add family fee to income
      await prisma.finance.update({
        where: { id: financeRecord.id },
        data: {
          income: financeRecord.income + familyFee.paidAmount,
          paidFeesCount: financeRecord.paidFeesCount + familyFee.students.length
        }
      });
    }

    res.status(200).json({
      message: "Family fee payment processed successfully",
      familyFee: updatedFamilyFee
    });
  } catch (error) {
    console.error("Error processing family fee payment:", error);
    res.status(500).json({ message: "Server error", error: error.message });
  }
};

// Delete family fee record
export const deleteFamilyFee = async (req, res) => {
  try {
    const { id } = req.params;

    const familyFee = await prisma.familyFee.findUnique({
      where: { id },
      include: { students: true }
    });
    
    if (!familyFee) {
      return res.status(404).json({ message: "Family fee record not found" });
    }

    // Adjust finance if needed
    const financeRecord = await prisma.finance.findFirst({
      where: {
        month: familyFee.month,
        year: familyFee.year
      }
    });

    if (financeRecord) {
      // If it was fully paid, remove income and counts
      if (familyFee.paid) {
        const newIncome = Math.max(0, (financeRecord.income || 0) - (familyFee.paidAmount || 0));
        const newPaidFeesCount = Math.max(0, (financeRecord.paidFeesCount || 0) - familyFee.students.length);
        
        await prisma.finance.update({
          where: { id: financeRecord.id },
          data: {
            income: newIncome,
            paidFeesCount: newPaidFeesCount,
            lastUpdated: new Date()
          }
        });
      } else {
        // If not fully paid, remove the outstanding amount from debt and any partial income
        const remaining = Math.max((familyFee.totalAmount || 0) - (familyFee.paidAmount || 0), 0);
        const newDebt = Math.max(0, (financeRecord.debt || 0) - remaining);
        const newIncome = Math.max(0, (financeRecord.income || 0) - (familyFee.paidAmount || 0));
        
        await prisma.finance.update({
          where: { id: financeRecord.id },
          data: {
            debt: newDebt,
            income: newIncome,
            lastUpdated: new Date()
          }
        });
      }
    }

    await prisma.familyFee.delete({
      where: { id }
    });

    res.status(200).json({
      message: "Family fee record deleted successfully"
    });
  } catch (error) {
    console.error("Error deleting family fee:", error);
    res.status(500).json({ message: "Server error", error: error.message });
  }
};

// Get family fee statistics
export const getFamilyFeeStatistics = async (req, res) => {
  try {
    const { month, year } = req.query;
    
    let where = {};
    if (month) where.month = parseInt(month);
    if (year) where.year = parseInt(year);

    const totalFamilies = await prisma.familyFee.count({ where });
    const paidFamilies = await prisma.familyFee.count({ 
      where: { ...where, paid: true } 
    });
    const unpaidFamilies = totalFamilies - paidFamilies;

    const totalAmountAgg = await prisma.familyFee.aggregate({
      where,
      _sum: { totalAmount: true }
    });

    const paidAmountAgg = await prisma.familyFee.aggregate({
      where: { ...where, paidAmount: { gt: 0 } },
      _sum: { paidAmount: true }
    });

    const totalAmount = totalAmountAgg._sum.totalAmount || 0;
    const paidAmount = paidAmountAgg._sum.paidAmount || 0;

    // Count total students in families
    const studentCountResult = await prisma.familyFeeStudent.count({
      where: {
        familyFee: where
      }
    });

    const totalStudentsInFamilies = studentCountResult;

    res.status(200).json({
      message: "Family fee statistics retrieved successfully",
      statistics: {
        totalFamilies,
        paidFamilies,
        unpaidFamilies,
        totalAmount,
        paidAmount,
        unpaidAmount: totalAmount - paidAmount,
        totalStudentsInFamilies,
        paymentRate: totalFamilies > 0 ? ((paidFamilies / totalFamilies) * 100).toFixed(2) : 0
      }
    });
  } catch (error) {
    console.error("Error fetching family fee statistics:", error);
    res.status(500).json({ message: "Server error", error: error.message });
  }
};