// Update fee record (mark as paid/unpaid)
export const updateFeeRecord = async (req, res) => {
  try {
    const { feeId } = req.params;
    const { paid, paidDate, note, amount, dueDate } = req.body;

    const feeRecord = await prisma.fee.findUnique({
      where: { id: feeId }
    });
    if (!feeRecord) {
      return res.status(404).json({ message: "Diiwaanka lacagta lama helin" });
    }

    const prevPaid = !!feeRecord.paid;
    const prevAmount = Number(feeRecord.amount || 0);
    const newAmount = amount !== undefined && !isNaN(amount) ? Number(amount) : Number(feeRecord.amount || 0);
    const newPaid = paid !== undefined ? !!paid : prevPaid;

    const updateData = {
      amount: newAmount,
      dueDate: dueDate !== undefined ? new Date(dueDate) : feeRecord.dueDate,
      note: note !== undefined ? note : feeRecord.note,
      paid: newPaid,
      paidDate: newPaid ? (paidDate ? new Date(paidDate) : feeRecord.paidDate || new Date()) : null
    };

    const updatedFee = await prisma.fee.update({
      where: { id: feeId },
      data: updateData,
      include: {
        student: { select: { fullname: true } },
        class: { select: { name: true } },
        createdBy: { select: { username: true } }
      }
    });

    const finance = await getOrCreateMonthlyFinance(updatedFee.month, updatedFee.year);
    const financeUpdates = {};

    if (prevPaid !== newPaid) {
      if (newPaid) {
        financeUpdates.income = { increment: newAmount };
        financeUpdates.debt = { decrement: prevAmount };
        financeUpdates.paidFeesCount = { increment: 1 };
        financeUpdates.unpaidFeesCount = { decrement: 1 };
      } else {
        financeUpdates.income = { decrement: prevAmount };
        financeUpdates.debt = { increment: newAmount };
        financeUpdates.paidFeesCount = { decrement: 1 };
        financeUpdates.unpaidFeesCount = { increment: 1 };
      }
    } else {
      const delta = newAmount - prevAmount;
      if (delta !== 0) {
        if (newPaid) {
          financeUpdates.income = { increment: delta };
        } else {
          financeUpdates.debt = { increment: delta };
        }
      }
    }

    await prisma.finance.update({
      where: { id: finance.id },
      data: {
        ...financeUpdates,
        lastUpdated: new Date()
      }
    });

    return res.status(200).json({
      message: "Diiwaanka lacagta si guul leh ayaa loo cusboonaysiiyay",
      feeRecord: updatedFee
    });
  } catch (error) {
    console.error("Error updating fee record:", error);
    return res.status(500).json({ message: "Khalad ayaa dhacay diiwaanka lacagta cusboonaysiinta" });
  }
};

// Delete fee record
export const deleteFeeRecord = async (req, res) => {
  try {
    const { feeId } = req.params;

    const feeRecord = await prisma.fee.findUnique({
      where: { id: feeId }
    });
    if (!feeRecord) {
      return res.status(404).json({ message: "Diiwaanka lacagta lama helin" });
    }

    const finance = await getOrCreateMonthlyFinance(feeRecord.month, feeRecord.year);
    const financeUpdates = {};
    if (feeRecord.paid) {
      financeUpdates.income = { decrement: feeRecord.amount };
      financeUpdates.paidFeesCount = { decrement: 1 };
    } else {
      financeUpdates.debt = { decrement: feeRecord.amount };
      financeUpdates.unpaidFeesCount = { decrement: 1 };
    }

    await prisma.fee.delete({ where: { id: feeId } });
    await prisma.finance.update({
      where: { id: finance.id },
      data: {
        ...financeUpdates,
        lastUpdated: new Date()
      }
    });

    return res.status(200).json({
      message: "Diiwaanka lacagta si guul leh ayaa loo tirtay"
    });
  } catch (error) {
    console.error("Error deleting fee record:", error);
    return res.status(500).json({ message: "Khalad ayaa dhacay diiwaanka lacagta tirista" });
  }
};

// Get fee statistics
export const getFeeStatistics = async (req, res) => {
  try {
    const { month, year } = req.query;

    const filter = {};
    if (month) filter.month = parseInt(month, 10);
    if (year) filter.year = parseInt(year, 10);

    const totalFees = await prisma.fee.count({ where: filter });
    const paidFees = await prisma.fee.count({ where: { ...filter, paid: true } });
    const unpaidFees = totalFees - paidFees;

    const totalAmountResult = await prisma.fee.aggregate({
      _sum: { amount: true },
      where: filter
    });
    const paidAmountResult = await prisma.fee.aggregate({
      _sum: { amount: true },
      where: { ...filter, paid: true }
    });

    return res.status(200).json({
      message: "Tirakoobka lacagta si guul leh ayaa loo helay",
      statistics: {
        totalFees,
        paidFees,
        unpaidFees,
        totalAmount: totalAmountResult._sum.amount || 0,
        paidAmount: paidAmountResult._sum.amount || 0,
        unpaidAmount: (totalAmountResult._sum.amount || 0) - (paidAmountResult._sum.amount || 0)
      }
    });
  } catch (error) {
    console.error("Error getting fee statistics:", error);
    return res.status(500).json({ message: "Khalad ayaa dhacay tirakoobka lacagta soo bandhigista" });
  }
};