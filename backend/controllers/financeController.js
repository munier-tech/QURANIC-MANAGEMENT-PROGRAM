import prisma from "../lib/prismaClient.js";

export const AddFinance = async ( req, res ) => {
  try {
    const { income , expenses , debt  , date } = req.body;

    if (!income || !expenses || !debt || !date) {
      return res.status(400).json({ message: "Fadlan buuxi dhammaan meelaha banan" });
    }

    const finance = await prisma.finance.create({
      data: {
        income: Number(income),
        expenses: Number(expenses),
        debt: Number(debt),
        date: date ? new Date(date) : new Date()
      }
    });

    return res.status(201).json({ message: "Maalgelinta si guul leh ayaa loo abuuray", finance });
  } catch (error) {
    console.error("error in AddFinance function: ", error);
    return res.status(500).json({ message: error.message });
  }
}

// Auto-generate monthly finance summary
export const generateMonthlyFinance = async (req, res) => {
  try {
    const { month, year } = req.body;
    
    if (!month || !year) {
      return res.status(400).json({ message: "Fadlan buuxi bisha iyo sanadka" });
    }

    const monthNum = parseInt(month);
    const yearNum = parseInt(year);

    // Calculate total student fees (income) for the month
    const studentFeesResult = await prisma.fee.aggregate({
      _sum: { amount: true },
      _count: true,
      where: {
        month: monthNum,
        year: yearNum,
        paid: true
      }
    });

    const totalIncome = studentFeesResult._sum.amount || 0;
    const paidFeesCount = studentFeesResult._count;

    // Calculate total teacher salaries (expenses) for the month
    const teacherSalariesResult = await prisma.salary.aggregate({
      _sum: { totalAmount: true },
      _count: true,
      where: {
        month: monthNum,
        year: yearNum,
        paid: true
      }
    });

    const totalExpenses = teacherSalariesResult._sum.totalAmount || 0;
    const paidSalariesCount = teacherSalariesResult._count;

    // Calculate unpaid fees (debt)
    const unpaidFeesResult = await prisma.fee.aggregate({
      _sum: { amount: true },
      _count: true,
      where: {
        month: monthNum,
        year: yearNum,
        paid: false
      }
    });

    const totalDebt = unpaidFeesResult._sum.amount || 0;
    const unpaidFeesCount = unpaidFeesResult._count;

    // Check if finance record already exists for this month
    const existingFinance = await prisma.finance.findFirst({
      where: {
        month: monthNum,
        year: yearNum
      }
    });

    if (existingFinance) {
      // Update existing record
      const updatedFinance = await prisma.finance.update({
        where: { id: existingFinance.id },
        data: {
          income: totalIncome,
          expenses: totalExpenses,
          debt: totalDebt,
          paidFeesCount,
          paidSalariesCount,
          unpaidFeesCount,
          lastUpdated: new Date()
        }
      });
      
      return res.status(200).json({ 
        message: "Maalgelinta bishan si guul leh ayaa loo cusboonaysiiyay", 
        finance: updatedFinance 
      });
    } else {
      // Create new finance record
      const finance = await prisma.finance.create({
        data: {
          income: totalIncome,
          expenses: totalExpenses,
          debt: totalDebt,
          month: monthNum,
          year: yearNum,
          paidFeesCount,
          paidSalariesCount,
          unpaidFeesCount,
          date: new Date(yearNum, monthNum - 1, 1),
          isAutoGenerated: true
        }
      });

      return res.status(201).json({ 
        message: "Maalgelinta bishan si guul leh ayaa loo abuuray", 
        finance 
      });
    }
  } catch (error) {
    console.error("error in generateMonthlyFinance function: ", error);
    return res.status(500).json({ message: error.message });
  }
}

