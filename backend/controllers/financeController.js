// Get finance summary with detailed breakdown
export const getFinanceSummary = async (req, res) => {
  try {
    const { month, year } = req.query;
    
    if (!month || !year) {
      return res.status(400).json({ message: "Fadlan dooro bisha iyo sanadka" });
    }

    const monthNum = parseInt(month);
    const yearNum = parseInt(year);

    // Get total student fees for the month (income)
    const studentFeesTotal = await prisma.fee.aggregate({
      _sum: { amount: true },
      _count: true,
      where: {
        month: monthNum,
        year: yearNum,
        paid: true
      }
    });

    // Get total teacher salaries for the month (expenses)
    const teacherSalariesTotal = await prisma.salary.aggregate({
      _sum: { totalAmount: true },
      _count: true,
      where: {
        month: monthNum,
        year: yearNum,
        paid: true
      }
    });

    // Get unpaid fees (debt)
    const unpaidFeesTotal = await prisma.fee.aggregate({
      _sum: { amount: true },
      _count: true,
      where: {
        month: monthNum,
        year: yearNum,
        paid: false
      }
    });

    // Get manual finance records for the month
    const startDate = new Date(yearNum, monthNum - 1, 1);
    const endDate = new Date(yearNum, monthNum, 0);
    
    const manualFinance = await prisma.finance.findMany({
      where: {
        date: {
          gte: startDate,
          lte: endDate
        },
        isAutoGenerated: false
      },
      orderBy: { createdAt: 'desc' }
    });

    // Get auto-generated finance record for the month
    const autoFinance = await prisma.finance.findFirst({
      where: {
        month: monthNum,
        year: yearNum,
        isAutoGenerated: true
      }
    });

    const summary = {
      month: monthNum,
      year: yearNum,
      income: studentFeesTotal._sum.amount || 0,
      expenses: teacherSalariesTotal._sum.totalAmount || 0,
      debt: unpaidFeesTotal._sum.amount || 0,
      paidFeesCount: studentFeesTotal._count,
      paidSalariesCount: teacherSalariesTotal._count,
      unpaidFeesCount: unpaidFeesTotal._count,
      manualFinance,
      autoFinance,
      netProfit: (studentFeesTotal._sum.amount || 0) - (teacherSalariesTotal._sum.totalAmount || 0)
    };

    return res.status(200).json({ 
      message: "Faahfaahinta maalgelinta si guul leh ayaa loo helay", 
      summary
    });
  } catch (error) {
    console.error("error in getFinanceSummary function: ", error);
    return res.status(500).json({ message: error.message });
  }
}

// Get monthly breakdown for the entire year
export const getYearlyFinanceBreakdown = async (req, res) => {
  try {
    const { year } = req.query;
    
    if (!year) {
      return res.status(400).json({ message: "Fadlan dooro sanadka" });
    }

    const yearNum = parseInt(year);

    // Get monthly breakdown of student fees
    const monthlyFees = await prisma.fee.groupBy({
      by: ['month'],
      _sum: { amount: true },
      _count: true,
      where: {
        year: yearNum,
        paid: true
      },
      orderBy: { month: 'asc' }
    });

    // Get monthly breakdown of teacher salaries
    const monthlySalaries = await prisma.salary.groupBy({
      by: ['month'],
      _sum: { totalAmount: true },
      _count: true,
      where: {
        year: yearNum,
        paid: true
      },
      orderBy: { month: 'asc' }
    });

    // Get monthly breakdown of unpaid fees (students)
    const monthlyUnpaidFees = await prisma.fee.groupBy({
      by: ['month'],
      _sum: { amount: true },
      _count: true,
      where: {
        year: yearNum,
        paid: false
      },
      orderBy: { month: 'asc' }
    });

    // Create monthly breakdown
    const monthlyBreakdown = [];
    for (let month = 1; month <= 12; month++) {
      const feesData = monthlyFees.find(f => f.month === month) || { _sum: { amount: 0 }, _count: 0 };
      const salariesData = monthlySalaries.find(s => s.month === month) || { _sum: { totalAmount: 0 }, _count: 0 };
      const unpaidData = monthlyUnpaidFees.find(u => u.month === month) || { _sum: { amount: 0 }, _count: 0 };

      monthlyBreakdown.push({
        month,
        income: feesData._sum.amount || 0,
        expenses: salariesData._sum.totalAmount || 0,
        debt: unpaidData._sum.amount || 0,
        paidFeesCount: feesData._count,
        paidSalariesCount: salariesData._count,
        unpaidFeesCount: unpaidData._count,
        netProfit: (feesData._sum.amount || 0) - (salariesData._sum.totalAmount || 0)
      });
    }

    const totalIncome = monthlyFees.reduce((sum, f) => sum + (f._sum.amount || 0), 0);
    const totalExpenses = monthlySalaries.reduce((sum, s) => sum + (s._sum.totalAmount || 0), 0);
    const totalDebt = monthlyUnpaidFees.reduce((sum, u) => sum + (u._sum.amount || 0), 0);
    const totalPaidFees = monthlyFees.reduce((sum, f) => sum + f._count, 0);
    const totalPaidSalaries = monthlySalaries.reduce((sum, s) => sum + s._count, 0);
    const totalUnpaidFees = monthlyUnpaidFees.reduce((sum, u) => sum + u._count, 0);

    return res.status(200).json({ 
      message: "Faahfaahinta maalgelinta sanadka si guul leh ayaa loo helay", 
      yearlyBreakdown: {
        year: yearNum,
        monthlyBreakdown,
        totalIncome,
        totalExpenses,
        totalDebt,
        totalPaidFees,
        totalPaidSalaries,
        totalUnpaidFees
      }
    });
  } catch (error) {
    console.error("error in getYearlyFinanceBreakdown function: ", error);
    return res.status(500).json({ message: error.message });
  }
}

